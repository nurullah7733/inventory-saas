import assert from "node:assert/strict";
import { checkoutPayment } from "../lib/sales/checkout-payment.ts";
import { preferredInvoicePaper, rememberInvoicePaper } from "../lib/client/invoice-print-preference.ts";
assert.deepEqual(checkoutPayment("850.00", "1000.00", "cash"), { paidAmount: "850.00", change: "150.00", due: "0.00" });
assert.deepEqual(checkoutPayment("850.00", "500.00", "cash"), { paidAmount: "500.00", change: "0.00", due: "350.00" });
assert.deepEqual(checkoutPayment("10.05", "20.1", "cash"), { paidAmount: "10.05", change: "10.05", due: "0.00" });
assert.deepEqual(checkoutPayment("0.00", "1.00", "cash"), { paidAmount: "0.00", change: "1.00", due: "0.00" });
for (const method of ["card", "bank", "mobile", null]) assert.throws(() => checkoutPayment("10.00", "11.00", method), /cannot exceed/);
for (const received of ["-1", "1e3", "NaN", "1.001", "", "100000000"]) assert.throws(() => checkoutPayment("10.00", received, "cash"), /valid payment/);
const storage = new Map<string, string>();
Object.defineProperty(globalThis, "localStorage", { configurable: true, value: { getItem: (key: string) => storage.get(key) ?? null, setItem: (key: string, value: string) => storage.set(key, value) } });
assert.equal(preferredInvoicePaper("shop-a", "thermal"), "thermal");
rememberInvoicePaper("shop-a", "a4");
assert.equal(preferredInvoicePaper("shop-a", "thermal"), "a4");
assert.equal(preferredInvoicePaper("shop-b", "thermal"), "thermal");
Object.defineProperty(globalThis, "localStorage", { configurable: true, get: () => { throw new Error("blocked"); } });
assert.equal(preferredInvoicePaper("shop-a", "a4"), "a4");
assert.doesNotThrow(() => rememberInvoicePaper("shop-a", "thermal"));
console.log("Checkout payment and paper preference checks passed.");
