import assert from "node:assert/strict";
import { chartPeriod, previousPeriod, netAmount, grossProfit, periodComparison, kpiComparison, returnPercentage, formatKpiPercentage } from "../lib/dashboard/insights-calculations.ts";
import { insightsFilterSchema } from "../lib/dashboard/insights-types.ts";
import { canViewFinance } from "../lib/dashboard/permissions.ts";

assert.equal(netAmount("5000.00", "200.00"), "4800.00");
assert.equal(returnPercentage("0.00", "0.00"), null);
assert.equal(returnPercentage("100.00", "0.00"), null);
assert.deepEqual(returnPercentage("0.00", "100.00"), { percentage: "0.00", barPercent: 0 });
assert.deepEqual(returnPercentage("25.00", "100.00"), { percentage: "25.00", barPercent: 25 });
assert.deepEqual(returnPercentage("1.00", "3.00"), { percentage: "33.33", barPercent: 33.33 });
assert.deepEqual(returnPercentage("100.00", "100.00"), { percentage: "100.00", barPercent: 100 });
assert.deepEqual(returnPercentage("150.00", "100.00"), { percentage: "150.00", barPercent: 100 });
assert.deepEqual(returnPercentage("9007199254740993.00", "9007199254740993.00"), { percentage: "100.00", barPercent: 100 });
assert.equal(netAmount("0.00", "20.01"), "-20.01");
assert.equal(grossProfit("4800.00", "3000.00"), "1800.00");
assert.equal(grossProfit("-20.00", "-10.00"), "-10.00");
assert.equal(netAmount("9007199254740993.01", "0.01"), "9007199254740993.00");
assert.equal(periodComparison("125.00", "100.00"), "25.00");
assert.equal(periodComparison("75.00", "100.00"), "-25.00");
assert.equal(periodComparison("-50.00", "-100.00"), "50.00");
assert.equal(periodComparison("0.00", "0.00"), "0.00");
assert.equal(periodComparison("100.00", "0.00"), null);
assert.equal(periodComparison("-100.00", "0.00"), null);
for (const expense of [false, true]) {
  assert.deepEqual(kpiComparison("0.00", "0.00", expense), { label: "— No change", tone: "neutral" });
  assert.deepEqual(kpiComparison("100.00", "0.00", expense), { label: "New", tone: "positive" });
  assert.deepEqual(kpiComparison("0.00", "100.00", expense), { label: "▼ 100% vs previous period", tone: expense ? "positive" : "negative" });
  assert.equal(kpiComparison("125.00", "100.00", expense).tone, expense ? "negative" : "positive");
  assert.equal(kpiComparison("75.00", "100.00", expense).tone, expense ? "positive" : "negative");
  assert.equal(kpiComparison("-50.00", "-100.00", expense).tone, "neutral");
  assert.equal(kpiComparison("-100.00", "0.00", expense).tone, "neutral");
}
assert.equal(formatKpiPercentage("25.00"), "25.0");
assert.equal(formatKpiPercentage("33.33"), "33.3");
assert.equal(formatKpiPercentage("33.35"), "33.4");
assert.equal(formatKpiPercentage("100.00"), "100");
assert.equal(formatKpiPercentage("1427.00"), "1,427");
assert.equal(formatKpiPercentage("1427.50"), "1,428");
assert.equal(formatKpiPercentage("-1427.00"), "1,427");
assert.equal(formatKpiPercentage("9007199254740993.00"), "9,007,199,254,740,993");
assert.deepEqual(kpiComparison("1527.00", "100.00"), { label: "▲ 1,427% vs previous period", tone: "positive" });
assert.deepEqual(kpiComparison("1527.00", "100.00", true), { label: "▲ 1,427% vs previous period", tone: "negative" });
assert.equal(periodComparison("2.00", "3.00"), "-33.33");
assert.equal(periodComparison("9007199254740993.00", "9007199254740993.00"), "0.00");
assert.deepEqual(previousPeriod({ from: "2026-03-01", to: "2026-03-31" }), { from: "2026-01-29", to: "2026-02-28" });
assert.deepEqual(previousPeriod({ from: "2024-03-01", to: "2024-03-01" }), { from: "2024-02-29", to: "2024-02-29" });
const period = { from: "2026-10-01", to: "2026-10-09" };
assert.deepEqual(chartPeriod(period, "selected", "2026-10-09"), period);
assert.deepEqual(chartPeriod(period, "7d", "2026-10-09"), { from: "2026-10-03", to: "2026-10-09" });
assert.deepEqual(chartPeriod(period, "30d", "2026-10-09"), { from: "2026-09-10", to: "2026-10-09" });
assert.deepEqual(chartPeriod(period, "12m", "2026-10-09"), { from: "2025-11-01", to: "2026-10-09" });
assert.deepEqual(chartPeriod(period, "12m", "2026-12-31"), { from: "2026-01-01", to: "2026-12-31" });
assert.equal(insightsFilterSchema.safeParse({ ...period, section: "finance" }).success, true);
for (const value of [{ ...period, section: "invalid" }, { ...period, tenantId: "spoof" }, { from: "2026-01-01", to: "2026-12-31" }, { from: "2026-02-30", to: "2026-03-01" }]) assert.equal(insightsFilterSchema.safeParse(value).success, false);
assert.equal(canViewFinance("staff"), false); assert.equal(canViewFinance("manager"), true); assert.equal(canViewFinance("shop_owner"), true);
console.log("Dashboard insight tests passed: exact net/gross, signed and zero-baseline percentages, previous ranges, chart windows, validation and role visibility.");
